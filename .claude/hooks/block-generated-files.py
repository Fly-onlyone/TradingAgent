#!/usr/bin/env python
"""PreToolUse hook: block edits to files owned by automation.

Blocks Edit/Write/MultiEdit on:
- CHANGELOG.md (owned by Release Please)
- .release-please-manifest.json (owned by Release Please)
- frontend/src/routeTree.gen.ts (auto-generated by @tanstack/router-plugin)
- package.json / pyproject.toml / Cargo.toml / tauri.conf.json *version field*
  (Release Please owns the version strings — but edits to other fields are OK,
  so we only block if the diff touches a version line).

Exit code 2 with a stderr message blocks the tool call.
"""

from __future__ import annotations

import json
import os
import re
import sys
from pathlib import Path

FULL_BLOCK = {
    "CHANGELOG.md",
    ".release-please-manifest.json",
    "frontend/src/routeTree.gen.ts",
}

# Files where only the version line is protected
VERSION_GUARDED = {
    "pyproject.toml": re.compile(r'^\s*version\s*=\s*"', re.MULTILINE),
    "frontend/package.json": re.compile(r'"version"\s*:\s*"'),
    "frontend/src-tauri/Cargo.toml": re.compile(r'^\s*version\s*=\s*"', re.MULTILINE),
    "frontend/src-tauri/tauri.conf.json": re.compile(r'"version"\s*:\s*"'),
}


def block(reason: str) -> int:
    print(f"BLOCKED by .claude/hooks/block-generated-files.py\n{reason}", file=sys.stderr)
    return 2


def main() -> int:
    try:
        payload = json.load(sys.stdin)
    except json.JSONDecodeError:
        return 0

    tool_input = payload.get("tool_input") or {}
    file_path = tool_input.get("file_path")
    if not file_path:
        return 0

    project_dir = os.environ.get("CLAUDE_PROJECT_DIR")
    if not project_dir:
        return 0

    project_root = Path(project_dir).resolve()
    target = Path(file_path).resolve()
    try:
        rel = target.relative_to(project_root).as_posix()
    except ValueError:
        return 0

    if rel in FULL_BLOCK:
        return block(
            f"{rel} is owned by automation (Release Please or generated).\n"
            f"Reason: hand-edits get overwritten and will break releases.\n"
            f"If this is intentional, edit via the automation config "
            f"(release-please-config.json / vite.config.ts route plugin)."
        )

    guard = VERSION_GUARDED.get(rel)
    if guard is not None:
        new_string = tool_input.get("new_string", "")
        old_string = tool_input.get("old_string", "")
        content = tool_input.get("content", "")
        if guard.search(new_string) or guard.search(old_string) or guard.search(content):
            return block(
                f"{rel}: version string is owned by Release Please.\n"
                f"Reason: merging the 'chore(release): vX.Y.Z' PR is the only way to bump versions."
            )

    return 0


if __name__ == "__main__":
    sys.exit(main())
