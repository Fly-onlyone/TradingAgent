"""Knowledge base models for RAG and trade learning (MongoDB/Beanie)."""

from datetime import UTC, datetime
from enum import Enum

from beanie import Document, Indexed, PydanticObjectId
from pydantic import Field, field_validator
from pymongo import ASCENDING, DESCENDING, TEXT, IndexModel


class TradeOutcome(str, Enum):
    """Normalized lesson outcomes."""

    PROFIT = "profit"
    LOSS = "loss"
    BREAKEVEN = "breakeven"


class TradeSide(str, Enum):
    """Normalized trade directions."""

    BUY = "buy"
    SELL = "sell"


class StrategyKnowledge(Document):
    """Knowledge base for trading strategies."""

    name: Indexed(str)  # type: ignore[valid-type]
    description: str

    # Strategy rules
    entry_rules: dict  # Conditions to enter trade
    exit_rules: dict  # Conditions to exit
    risk_params: dict  # Position sizing, stop-loss

    # Performance metrics
    backtest_results: dict | None = None
    win_rate: float | None = None
    avg_return: float | None = None
    max_drawdown: float | None = None
    sharpe_ratio: float | None = None

    # Rating aggregates
    overall_rating: float | None = None
    rating_confidence: float | None = None
    rating_count: int = 0
    average_user_rating: float | None = None

    # Metadata
    market_conditions: list[str] | None = None  # Best conditions for strategy
    asset_classes: list[str] | None = None  # Suitable assets
    timeframes: list[str] | None = None  # Suitable timeframes

    # Provenance — traces back to the source that produced this knowledge entry
    source_article_id: PydanticObjectId | None = None  # FK → NewsArticle (auto-discovery)
    source_url: str | None = None  # Original URL (article or user-provided import)
    source_sentiment: float | None = Field(
        default=None,
        ge=-1.0,
        le=1.0,
    )  # Sentiment of the source article at extraction time
    # FK → AgentSession for the extractor subagent run that produced this strategy
    source_session_id: PydanticObjectId | None = None

    # Extraction conversation history (populated during AI import)
    extraction_messages: list[dict] = Field(default_factory=list)

    # Contextual prefix for improved embedding quality (generated by Claude)
    context_prefix: str | None = None

    # Embedding for semantic search (768-dim nomic-embed-text-v1.5 vector stored inline)
    embedding: list[float] | None = None

    created_at: datetime = Field(default_factory=lambda: datetime.now(UTC))
    updated_at: datetime = Field(default_factory=lambda: datetime.now(UTC))

    class Settings:
        name = "strategy_knowledge"
        use_state_management = True
        indexes = [
            IndexModel(
                [("created_at", DESCENDING)],
                name="strategy_knowledge_created_desc",
            ),
            IndexModel(
                [("overall_rating", DESCENDING)],
                name="strategy_knowledge_overall_rating_desc",
            ),
            IndexModel(
                [("name", TEXT), ("description", TEXT)],
                name="strategy_knowledge_text",
                default_language="english",
            ),
        ]

    def update_timestamp(self) -> None:
        """Update the updated_at timestamp."""
        self.updated_at = datetime.now(UTC)


class TradeLesson(Document):
    """Lessons learned from past trades."""

    order_id: PydanticObjectId | None = None

    # Trade outcome
    outcome: TradeOutcome
    profit_pct: float
    profit_amount: float | None = None

    # Lesson content
    lesson_summary: str  # AI-generated insight
    market_context: dict  # Market conditions during trade
    mistakes: list[str] | None = None  # What went wrong
    successes: list[str] | None = None  # What went right
    recommendations: list[str] | None = None  # Future improvements

    # Trade metadata
    symbol: Indexed(str)  # type: ignore[valid-type]
    side: TradeSide
    entry_price: float
    exit_price: float
    duration_minutes: int | None = None

    # Contextual prefix for improved embedding quality (generated by Claude)
    context_prefix: str | None = None

    # Embedding for semantic search (768-dim nomic-embed-text-v1.5 vector)
    embedding: list[float] | None = None

    created_at: datetime = Field(default_factory=lambda: datetime.now(UTC))

    @field_validator("outcome", mode="before")
    @classmethod
    def _normalize_outcome(cls, value: TradeOutcome | str) -> TradeOutcome:
        if isinstance(value, TradeOutcome):
            return value
        return TradeOutcome(value.strip().lower())

    @field_validator("side", mode="before")
    @classmethod
    def _normalize_side(cls, value: TradeSide | str) -> TradeSide:
        if isinstance(value, TradeSide):
            return value

        normalized = value.strip().lower()
        aliases = {
            "long": TradeSide.BUY,
            "short": TradeSide.SELL,
        }
        if normalized in aliases:
            return aliases[normalized]

        return TradeSide(normalized)

    class Settings:
        name = "trade_lessons"
        use_state_management = True
        indexes = [
            IndexModel(
                [("symbol", ASCENDING), ("created_at", DESCENDING)],
                name="trade_lessons_symbol_created_desc",
            ),
            IndexModel(
                [("outcome", ASCENDING), ("created_at", DESCENDING)],
                name="trade_lessons_outcome_created_desc",
            ),
            IndexModel(
                [("lesson_summary", TEXT)],
                name="trade_lessons_text",
                default_language="english",
            ),
        ]


class TradingPattern(Document):
    """Recognized trading patterns from historical data."""

    # Pattern info
    pattern_name: Indexed(str)  # type: ignore[valid-type]
    pattern_type: str  # 'technical', 'sentiment', 'correlation'
    description: str

    # Pattern definition
    conditions: dict  # Pattern conditions

    # Performance metrics
    success_rate: float
    sample_count: int
    avg_return: float
    avg_duration_hours: int | None = None

    # Applicability
    symbols: list[str] | None = None  # Symbols where pattern works
    timeframes: list[str] | None = None  # Best timeframes
    market_conditions: list[str] | None = None  # Best conditions

    # Contextual prefix for improved embedding quality (generated by Claude)
    context_prefix: str | None = None

    # Embedding for semantic search (768-dim nomic-embed-text-v1.5 vector)
    embedding: list[float] | None = None

    created_at: datetime = Field(default_factory=lambda: datetime.now(UTC))
    last_validated: datetime | None = None

    class Settings:
        name = "trading_patterns"
        use_state_management = True
        indexes = [
            IndexModel(
                [("pattern_type", ASCENDING), ("success_rate", DESCENDING)],
                name="trading_patterns_type_success_desc",
            ),
            IndexModel(
                [("pattern_name", TEXT), ("description", TEXT)],
                name="trading_patterns_text",
                default_language="english",
            ),
        ]


class KnowledgeChunk(Document):
    """A chunk of a larger knowledge document, for fine-grained retrieval."""

    parent_id: PydanticObjectId  # FK to the parent document
    parent_collection: str  # e.g. "news_articles", "strategy_knowledge"
    chunk_index: int
    total_chunks: int
    text: str
    embedding: list[float] | None = None
    created_at: datetime = Field(default_factory=lambda: datetime.now(UTC))

    class Settings:
        name = "knowledge_chunks"
        use_state_management = True
        indexes = [
            IndexModel(
                [("parent_id", ASCENDING), ("chunk_index", ASCENDING)],
                name="chunks_parent_idx",
            ),
        ]


